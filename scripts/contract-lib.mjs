// Turns the parsed contract (contract/openapi.yaml) into the data the core needs at run time.
// Pure function: used by scripts/gen-contract.mjs and by the test that checks the generated
// file is up to date.

const METHODS = ["get", "put", "post", "patch", "delete"];

function resolve(doc, node, seen = []) {
  if (Array.isArray(node)) return node.map((n) => resolve(doc, n, seen));
  if (node === null || typeof node !== "object") return node;
  if (typeof node.$ref === "string") {
    const ref = node.$ref;
    if (seen.includes(ref)) throw new Error("circular $ref " + ref);
    const target = ref.replace(/^#\//, "").split("/").reduce((o, k) => o[k], doc);
    return resolve(doc, target, [...seen, ref]);
  }
  const out = {};
  for (const [k, v] of Object.entries(node)) {
    if (k === "discriminator") {
      // Keep the property name and which variant each value selects (index into oneOf).
      const refs = (node.oneOf ?? []).map((s) => s.$ref);
      const map = {};
      for (const [value, ref] of Object.entries(v.mapping ?? {})) map[value] = refs.indexOf(ref);
      out["x-discriminator"] = { property: v.propertyName, map };
      continue;
    }
    out[k] = resolve(doc, v, seen);
  }
  return out;
}

function toolArgName(param) {
  return param.in === "header" ? param.name.toLowerCase().replace(/-/g, "_") : param.name;
}

export function buildContract(doc) {
  const operations = [];
  const tools = [];
  for (const [path, item] of Object.entries(doc.paths)) {
    const shared = resolve(doc, item.parameters ?? []);
    for (const method of METHODS) {
      const op = item[method];
      if (!op) continue;
      const security = op.security ?? doc.security ?? [];
      const scheme = security.length === 0 ? null : Object.keys(security[0])[0];
      const auth =
        scheme === null ? "none" : scheme === "deviceCredential" ? "device" : scheme === "pollSecret" ? "poll" : "assistant";
      const params = [...shared, ...resolve(doc, op.parameters ?? [])].map((p) => ({
        name: p.name,
        in: p.in,
        required: p.required === true,
        schema: p.schema ?? { type: "string" },
        ...(p.description ? { description: p.description } : {}),
      }));
      const content = op.requestBody?.content ?? {};
      const bodyType = Object.keys(content)[0] ?? null;
      const body = bodyType ? resolve(doc, content[bodyType].schema) : null;
      operations.push({
        operationId: op.operationId,
        method: method.toUpperCase(),
        path,
        auth,
        tier: op["x-tier"] ?? null,
        tool: op["x-mcp-tool"] ?? null,
        readOnly: op["x-mcp-readonly"] === true,
        idempotent: params.some((p) => p.in === "header" && p.name === "Idempotency-Key"),
        params,
        bodyType,
        bodyRequired: op.requestBody?.required === true,
        body,
      });
      if (op["x-mcp-tool"]) {
        const properties = {};
        const required = [];
        for (const p of params) {
          const name = toolArgName(p);
          properties[name] = p.description ? { ...p.schema, description: p.description } : p.schema;
          if (p.required) required.push(name);
        }
        if (body) {
          Object.assign(properties, body.properties ?? {});
          required.push(...(body.required ?? []));
        }
        tools.push({
          name: op["x-mcp-tool"],
          operationId: op.operationId,
          description: [op.summary, op.description].filter(Boolean).join("\n").trim(),
          readOnly: op["x-mcp-readonly"] === true,
          inputSchema: { type: "object", properties, required, additionalProperties: false },
        });
      }
    }
  }
  const flows = doc.components.securitySchemes.assistantCredential.flows.authorizationCode;
  return {
    version: doc.info.version,
    limits: doc["x-limits"],
    sharedRules: doc["x-shared-rules"],
    errorCodes: Object.keys(doc["x-error-codes"]),
    steps: Object.keys(flows.scopes),
    enums: Object.fromEntries(
      Object.entries(doc.components.schemas)
        .filter(([, s]) => Array.isArray(s.enum))
        .map(([name, s]) => [name, s.enum]),
    ),
    operations,
    tools,
  };
}

export function renderModule(contract) {
  return (
    "// GENERATED by `npm run gen` from contract/openapi.yaml. Do not edit.\n" +
    'import type { Contract } from "../contract-types";\n\n' +
    "export const CONTRACT: Contract = " +
    JSON.stringify(contract, null, 2) +
    ";\n"
  );
}
